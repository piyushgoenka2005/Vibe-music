/**
 * Generates header markup strings + thin React wrappers.
 * Run: node scripts/generate-header-components.mjs
 */
import fs from "fs";
import path from "path";

const ROOT = process.cwd();
const SRC = path.join(ROOT, "src/content/header.html");
const OUT = path.join(ROOT, "src/components/layout/Header");
const MARKUP = path.join(OUT, "generated/markup.ts");

const LOGO_PATH = "/logo.jpeg";

function normalizeHtml(html) {
  return html
    .replace(
      /https:\/\/media\.vibemusic\.in\/m\/header\/logo\/vibemusic-logo__new\.svg/gi,
      LOGO_PATH
    )
    .replace(
      /https:\/\/(?:media|assets|cdn)\.vibemusic\.in(\/[^"'\\s)<]+)/gi,
      (_, pathname) => `/images${pathname.split("?")[0]}`
    )
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "")
    .replace(/\sonclick="[^"]*"/gi, "")
    .replace(/\sonsubmit="[^"]*"/gi, "")
    .replace(/\soncontextmenu="[^"]*"/gi, "")
    .trim();
}

function escapeForTemplateLiteral(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function exportMarkup(name, html) {
  return `export const ${name} = \`${escapeForTemplateLiteral(html)}\`;\n`;
}

const html = normalizeHtml(fs.readFileSync(SRC, "utf8"));

const adaEnd = html.indexOf('<section data-header-version');
const menuHeaderStart = html.indexOf('<header class="assets-site-header__menu"');
const navStart = html.indexOf('<nav class="assets-site-header__nav"');

let navDepth = 0;
let navEnd = -1;
for (let i = navStart; i < html.length; i++) {
  if (html.startsWith("<nav", i)) navDepth++;
  if (html.startsWith("</nav>", i)) {
    navDepth--;
    if (navDepth === 0) {
      navEnd = i + "</nav>".length;
      break;
    }
  }
}

const assetsHeaderEnd = html.indexOf("</section>", navEnd) + "</section>".length;
const mobileSearchStart = html.indexOf('<section id="mobile-search-container"');
const mobileSearchEnd =
  html.indexOf("</section>", mobileSearchStart) + "</section>".length;

const adaHtml = html.slice(0, adaEnd);
const assetsHeaderOpen = html.slice(adaEnd, menuHeaderStart);
const menuHeaderHtml = html.slice(menuHeaderStart, navStart);
const megaNavHtml = html.slice(navStart, navEnd);
const assetsHeaderClose = html.slice(navEnd, assetsHeaderEnd);
const mobileSearchHtml = html.slice(mobileSearchStart, mobileSearchEnd);
const headerTailHtml = html.slice(mobileSearchEnd);

const accountStart = menuHeaderHtml.indexOf(
  '<div class="assets-site-header__menu-item assets-site-header__menu-account-wrap"'
);
const cartWrapStart = menuHeaderHtml.indexOf(
  '<div class="assets-site-header__menu-item assets-site-header__menu-cart-wrap"'
);
const navToggleStart = menuHeaderHtml.indexOf(
  '<div class="assets-site-header__menu-item assets-site-header__menu-nav-toggle-wrap"'
);

const mainNavLogoSearch = menuHeaderHtml.slice(0, accountStart);
const accountHtml = menuHeaderHtml.slice(accountStart, cartWrapStart);
const cartHtml = menuHeaderHtml.slice(cartWrapStart, navToggleStart);
const navToggleHtml = menuHeaderHtml.slice(navToggleStart);

// Extract inline black-bar style to separate css file
const styleMatch = assetsHeaderOpen.match(/<style>([\s\S]*?)<\/style>/);
let topBarHtml = assetsHeaderOpen;
if (styleMatch) {
  topBarHtml = topBarHtml.replace(styleMatch[0], "");
  fs.mkdirSync(path.join(ROOT, "public"), { recursive: true });
  fs.writeFileSync(
    path.join(ROOT, "public/vibe-header-black-bar.css"),
    styleMatch[1],
    "utf8"
  );
}

fs.mkdirSync(path.dirname(MARKUP), { recursive: true });

let markupFile = "// Auto-generated by scripts/generate-header-components.mjs\n\n";
markupFile += exportMarkup("ADA_MARKUP", adaHtml);
markupFile += exportMarkup("TOP_BAR_MARKUP", topBarHtml);
markupFile += exportMarkup("MAIN_NAV_LOGO_SEARCH_MARKUP", mainNavLogoSearch);
markupFile += exportMarkup("ACCOUNT_MENU_MARKUP", accountHtml);
markupFile += exportMarkup("CART_MENU_MARKUP", cartHtml);
markupFile += exportMarkup("NAV_TOGGLE_MARKUP", navToggleHtml);
markupFile += exportMarkup("MEGA_MENU_MARKUP", megaNavHtml);
markupFile += exportMarkup("ASSETS_HEADER_CLOSE_MARKUP", assetsHeaderClose);
markupFile += exportMarkup("MOBILE_SEARCH_MARKUP", mobileSearchHtml);
markupFile += exportMarkup("HEADER_TAIL_MARKUP", headerTailHtml);

fs.writeFileSync(MARKUP, markupFile, "utf8");

console.log("Wrote generated/markup.ts");
console.log("Sizes:", {
  ada: adaHtml.length,
  topBar: topBarHtml.length,
  mainNav: mainNavLogoSearch.length,
  account: accountHtml.length,
  cart: cartHtml.length,
  mega: megaNavHtml.length,
  mobile: mobileSearchHtml.length,
});
